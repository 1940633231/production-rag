"""Evaluation configuration loading and hashing."""

from __future__ import annotations

from pathlib import Path
from typing import Any

import yaml
from pydantic import Field, field_validator

from rag_eval.contracts import StrictModel, sha256_value


class EvaluationConfig(StrictModel):
    dataset: str = Field(min_length=1)
    adapter: str = Field(min_length=1)
    model: str | None = None
    prompt_version: str | None = None
    seed: int = 42
    max_errors: int = Field(default=0, ge=0)
    min_coverage: float = Field(default=1.0, ge=0.0, le=1.0)
    timeout_seconds: float = Field(default=60.0, gt=0.0)
    cache_dir: str | None = ".rag-eval-cache"
    output_dir: str = "reports/rag-eval"
    k_values: list[int] = Field(default_factory=lambda: [5, 10])
    thresholds: dict[str, float] = Field(default_factory=dict)
    allow_missing_metrics: bool = False
    metadata: dict[str, Any] = Field(default_factory=dict)

    @field_validator("k_values")
    @classmethod
    def validate_k_values(cls, values: list[int]) -> list[int]:
        if not values:
            raise ValueError("k_values must not be empty")
        if any(value <= 0 for value in values):
            raise ValueError("k_values must contain positive integers")
        return sorted(set(values))

    @field_validator("thresholds")
    @classmethod
    def validate_thresholds(cls, values: dict[str, float]) -> dict[str, float]:
        for metric, threshold in values.items():
            if not metric:
                raise ValueError("threshold metric names must not be blank")
            if threshold < 0:
                raise ValueError(f"threshold for {metric!r} must be non-negative")
        return values

    def config_hash(self) -> str:
        # Paths, thresholds, and gate-only switches do not change evaluation
        # semantics and must not invalidate a baseline generated by the same run.
        execution_config = self.model_dump(
            mode="json",
            exclude={
                "dataset",
                "cache_dir",
                "output_dir",
                "thresholds",
                "allow_missing_metrics",
            },
        )
        return sha256_value(execution_config)


def load_eval_config(path: str | Path) -> EvaluationConfig:
    config_path = Path(path)
    try:
        raw = yaml.safe_load(config_path.read_text(encoding="utf-8-sig"))
    except FileNotFoundError as exc:
        raise ValueError(f"evaluation config not found: {config_path}") from exc
    except yaml.YAMLError as exc:
        raise ValueError(f"invalid YAML in {config_path}: {exc}") from exc
    if raw is None:
        raw = {}
    if not isinstance(raw, dict):
        raise ValueError(f"evaluation config must be a YAML object: {config_path}")
    return EvaluationConfig.model_validate(raw)
